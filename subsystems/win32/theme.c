static int g_id = THEME_95;
const LgTheme *g_theme = &THEMES[THEME_95];

const char *theme_name(int id) { return (id >= 0 && id < THEME_COUNT) ? THEMES[id].name : "?"; }
int theme_id(void) { return g_id; }

void theme_set(int id) {
    if (id < 0 || id >= THEME_COUNT) return;
    g_id = id; g_theme = &THEMES[id];
    char v[8]; int n = id, k = 0;                       /* itoa: supports ids >= 10 */
    if (n == 0) v[k++] = '0'; else { char t[8]; int j = 0; while (n) { t[j++] = (char)('0' + n % 10); n /= 10; } while (j) v[k++] = t[--j]; }
    v[k] = 0; sys_set_setting("theme", v);
    /* push caption + desktop colours into the WM's cached state; the desktop
     * recomposes every frame, so the rest (face/bevels via the theme macros)
     * updates automatically. */
    wm_set_title_colors(g_theme->title_lo, g_theme->title_hi);
    wm_set_desktop_color(g_theme->desktop);
}

void theme_init(void) {
    char v[8];
    if (sys_get_setting("theme", v, sizeof v) == 0 && v[0] >= '0' && v[0] <= '9') {
        int id = 0; for (const char *p = v; *p >= '0' && *p <= '9'; p++) id = id * 10 + (*p - '0');
        theme_set(id < THEME_COUNT ? id : THEME_95);
    } else theme_set(THEME_95);
}
